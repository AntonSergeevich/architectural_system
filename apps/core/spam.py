"""Отсев ботов на форме заявки.

Сайт попал в поиск — и вместе с людьми пришли рассылки. Капча кажется
очевидным ответом, но она берёт плату с того, кто ни в чём не виноват:
заказчик разбирает светофоры, чтобы попасть к дизайнеру. Поэтому здесь
три проверки, которые человек не замечает вовсе.

1. Ловушка. В форме стоит поле, которого нет на экране. Человек его
   не заполнит, потому что не увидит; бот заполняет всё подряд.
2. Секундомер. Форму открыли и отправили за две секунды — значит,
   её не читали. Живой человек столько времени тратит на одно поле.
3. Признаки рассылки. Ссылки и слова про продвижение сайтов, займы
   и криптовалюту — не то, с чем приходят к дизайнеру интерьера.

Первые две проверки отбивают заявку сразу: это не человек. Третья
не отбивает ничего — она ставит метку «спам», и заявка тихо ложится
в отдельный ящик, без уведомления в Telegram. Разница принципиальная:
ошибиться, приняв рассылку, значит потратить минуту Дарьи, а ошибиться,
отбив заявку, — потерять заказчика.
"""

import re

# Ссылка в любом виде: с протоколом, с www или просто домен. Заказчики
# тоже присылают ссылки — на планировку, на Pinterest, — поэтому одна
# ссылка сама по себе не приговор, а только очко в общую сумму.
LINK_RE = re.compile(
    r"(https?://|www\.|\b[a-z0-9-]+\.(?:ru|com|net|org|info|xyz|top|online|site|shop|club|biz)\b)",
    re.IGNORECASE,
)

# Слова, с которыми к дизайнеру интерьера не приходят. Список короткий
# и намеренно скучный: чем он длиннее, тем выше шанс поймать живого
# человека, который просто написал «продвижение» про свою работу.
WORDS = (
    "seo", "сео", "продвижени", "раскрутк", "трафик на сайт", "лиды",
    "оптимизац", "казино", "ставк", "букмекер", "крипт", "биткоин",
    "инвестиц", "заработок", "займ", "кредит под", "рассылк",
    "холодные звонки", "база клиентов", "накрутк", "подписчик",
)

# Сколько секунд человеку нужно, чтобы заполнить форму по-настоящему.
# Четыре — с большим запасом вниз: в форме девять полей.
MIN_SECONDS = 4
# Через сутки подпись формы считается протухшей. Столько живёт открытая
# вкладка, а не заполнение заявки.
MAX_SECONDS = 24 * 3600

# Порог, с которого заявка считается рассылкой.
SPAM_SCORE = 3


def verdict(message="", name="", same_ip_hour=0):
    """Насколько заявка похожа на рассылку.

    Возвращает пару: пометить ли спамом и почему. Причина нужна Дарье:
    метка без объяснения — это просто «система решила», и доверия к ней
    хватает ровно до первой ошибки.
    """
    text = f"{message} {name}".lower()
    score, reasons = 0, []

    links = len(LINK_RE.findall(text))
    if links:
        score += 2
        reasons.append("ссылки в сообщении")

    hits = [word for word in WORDS if word in text]
    if hits:
        score += 2 + len(hits)
        reasons.append("слова рассылки: " + ", ".join(hits[:3]))

    # Кириллицы нет вовсе — при том, что сайт русский и город один.
    # Само по себе это не приговор: бывает и латиница в имени.
    if message and not re.search(r"[а-яё]", text):
        score += 1
        reasons.append("ни одного русского слова")

    if same_ip_hour >= 3:
        score += 3
        reasons.append(f"с одного адреса за час: {same_ip_hour + 1}")

    return score >= SPAM_SCORE, "; ".join(reasons)
