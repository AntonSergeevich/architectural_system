"""Тексты о себе переезжают из шаблонов в настройки.

Раньше абзацы про Дарью были зашиты в HTML, а поле «Текст о себе»
дописывалось к ним. Правка в админке не заменяла текст, а удлиняла его —
и убрать зашитое было нельзя вовсе.

Здесь ровно то, что было в шаблонах, переносится в базу: слова остаются
теми же, но теперь их можно поправить.
"""

from django.db import migrations

INTRO = (
    "И это осознанный выбор, а не оправдание. Я делаю живую историю, "
    "а не копипасту: интерьер, который отражает конкретных людей, "
    "нельзя собрать по шаблону."
)

ABOUT = (
    "Я выбираю специалистов по человеку: по подаче, по стилистике, по тому, "
    "на одной ли мы волне. Механически выполненная услуга и работа с тем, "
    "с кем совпадаешь в ценностях, — это два разных результата. Думаю, "
    "ко мне приходят по той же причине.\n\n"
    "Мои люди — те, кто не сомневается. Кто знает, чего хочет, и не сверяет "
    "каждое решение с роднёй. Кто умеет доверять: заплатил — и ждёт результат, "
    "а не выжимает контроль по мелочам. И кто открыт к тому, чтобы дом "
    "получился про них, а не про чужой референс."
)


def fill(apps, schema_editor):
    SiteSettings = apps.get_model("core", "SiteSettings")
    for site in SiteSettings.objects.all():
        changed = []
        if not site.owner_intro:
            site.owner_intro = INTRO
            changed.append("owner_intro")
        # Текст «о себе» мог быть уже заполнен руками — тогда он и остаётся:
        # написанное человеком важнее нашей заготовки.
        if not site.owner_about:
            site.owner_about = ABOUT
            changed.append("owner_about")
        if changed:
            site.save(update_fields=changed)


def back(apps, schema_editor):
    """Обратно не чистим: текст мог быть уже поправлен, и стирать его
    при откате миграции значит потерять чужую работу."""


class Migration(migrations.Migration):
    dependencies = [("core", "0007_owner_texts")]
    operations = [migrations.RunPython(fill, back)]
