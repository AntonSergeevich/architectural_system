class Command(BaseCommand):
    help = "Создаёт юридические документы и шаблоны договоров"

    @transaction.atomic
    def handle(self, *args, **options):
        site = SiteSettings.get()
        fields = {
            "legal_name": site.legal_name,
            "inn": site.inn,
            "phone": site.phone,
            "email": site.email or "почта не указана",
        }

        documents = [
            (LegalDocument.Kind.PRIVACY, "Политика конфиденциальности", PRIVACY),
            (LegalDocument.Kind.CONSENT, "Согласие на обработку персональных данных", CONSENT),
            (LegalDocument.Kind.COOKIES, "Политика в отношении файлов cookie", COOKIES),
            (LegalDocument.Kind.OFFER, "Публичная оферта", OFFER),
        ]
        created = 0
        for kind, title, body in documents:
            _, was_created = LegalDocument.objects.get_or_create(
                kind=kind,
                defaults={"title": title, "body": body.format(**fields), "version": "1.0"},
            )
            created += int(was_created)

        templates = [
            (ContractTemplate.Kind.DESIGN, "Договор на разработку дизайн-проекта", DESIGN_CLAUSES),
            (ContractTemplate.Kind.SUPERVISION, "Договор на авторский надзор", SUPERVISION_CLAUSES),
            (ContractTemplate.Kind.PROCUREMENT, "Договор на комплектацию", PROCUREMENT_CLAUSES),
        ]
        for kind, title, clauses in templates:
            template, was_created = ContractTemplate.objects.get_or_create(
                kind=kind, defaults={"title": title, "version": "1.0"}
            )
            if not was_created:
                continue
            for order, (number, clause_title, text, plain, important) in enumerate(clauses, start=1):
                ContractClause.objects.create(
                    template=template,
                    number=number,
                    title=clause_title,
                    text=text,
                    plain_text=plain,
                    is_important=important,
                    order=order * 10,
                )

        self.stdout.write(
            self.style.SUCCESS(
                f"Готово. Документов создано: {created}, "
                f"шаблонов договоров: {ContractTemplate.objects.count()}.\n"
                "Тексты — рабочие заготовки. Перед публикацией их должен "
                "посмотреть юрист."
            )
        )
