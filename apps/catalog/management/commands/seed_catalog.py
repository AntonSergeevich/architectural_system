class Command(BaseCommand):
    help = "Наполняет каталог услуг, пресеты, этапы и тексты сайта"

    @transaction.atomic
    def handle(self, *args, **options):
        groups = {}
        for code, title, part, order in GROUPS:
            groups[code], _ = ModuleGroup.objects.update_or_create(
                code=code, defaults={"title": title, "house_part": part, "order": order}
            )

        created = updated = 0
        for order, data in enumerate(MODULES, start=1):
            data = dict(data)
            code = data.pop("code")
            group_code = data.pop("group", None)
            price = Decimal(data.pop("price"))
            for money_field in ("included_units", "extra_unit_price"):
                if money_field in data:
                    data[money_field] = Decimal(data[money_field])
            data["group"] = groups.get(group_code)
            data["order"] = order * 10

            module = ServiceModule.objects.filter(code=code).first()
            if module is None:
                ServiceModule.objects.create(code=code, price=price, **data)
                created += 1
                continue
            # Цену не трогаем: её правит Дарья, и обновление кода не должно
            # откатывать её решения.
            for field, value in data.items():
                setattr(module, field, value)
            module.save()
            updated += 1

        for code, title, description, factor, is_default, order in COMPLEXITIES:
            ComplexityFactor.objects.update_or_create(
                code=code,
                defaults={
                    "title": title,
                    "description": description,
                    "factor": Decimal(factor),
                    "is_default": is_default,
                    "order": order,
                },
            )

        for code, title, tagline, description, codes, is_default, order in PRESETS:
            preset, _ = Preset.objects.update_or_create(
                code=code,
                defaults={
                    "title": title,
                    "tagline": tagline,
                    "description": description,
                    "is_default": is_default,
                    "order": order,
                },
            )
            preset.modules.set(ServiceModule.objects.filter(code__in=codes))

        for number, title, description, client_does, days, client_days in STAGES:
            StageNorm.objects.update_or_create(
                number=number,
                defaults={
                    "title": title,
                    "description": description,
                    "what_client_does": client_does,
                    "working_days": days,
                    "client_days": client_days,
                },
            )

        for question, answer, order in OBJECTIONS:
            Objection.objects.update_or_create(
                question=question, defaults={"answer": answer, "order": order}
            )

        # Правила расчёта создаём со значениями по умолчанию: фикс до 20 м²
        # включён, коэффициент сложности выключен — Дарья пока сомневается,
        # нужен ли он. Включается галочкой в кабинете в любой момент.
        PricingSettings.get()

        site = SiteSettings.get()
        if not site.regulations:
            site.regulations = REGULATIONS
            site.save(update_fields=["regulations"])

        self.stdout.write(
            self.style.SUCCESS(
                f"Каталог готов: модулей создано {created}, обновлено {updated}. "
                f"Пресетов {Preset.objects.count()}, этапов {StageNorm.objects.count()}."
            )
        )
