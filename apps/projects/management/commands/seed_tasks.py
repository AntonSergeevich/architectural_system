class Command(BaseCommand):
    help = "Создаёт готовые формулировки задач для этапов проекта"

    @transaction.atomic
    def handle(self, *args, **options):
        created = 0
        for number, title, who, order in PRESETS:
            _, was_created = TaskPreset.objects.update_or_create(
                stage_number=number,
                title=title,
                defaults={"who": who, "order": order},
            )
            created += int(was_created)

        self.stdout.write(
            self.style.SUCCESS(
                f"Готовых задач: создано {created}, всего {TaskPreset.objects.count()}."
            )
        )
