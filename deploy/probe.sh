#!/usr/bin/env bash
# Стучимся в приложение так же, как это делает nginx, и печатаем код ответа.
#   ./deploy/probe.sh   →   200
#
# Отдельный файл, потому что проверка нужна двум скриптам — выкатке и
# health.sh — и однажды уже разъехалась: оба стучались на 127.0.0.1:8000,
# которого здесь нет. Gunicorn слушает не порт, а юникс-сокет, и порт
# всегда отвечал «не отвечает совсем» на живом сайте.
#
# Одного адреса сокета мало: приложение на бою проверяет заголовки.
#   Host              — иначе ALLOWED_HOSTS отдаст 400;
#   X-Forwarded-Proto — иначе SECURE_SSL_REDIRECT отдаст 301 на https.
# Оба заголовка nginx подставляет сам, здесь их приходится писать руками.
#
# Если приложение не ответило, причина уходит в поток ошибок — её печатает
# тот, кто нас вызвал. Без неё «000» ничего не объясняет: сокета нет,
# сокет есть да никто не слушает и приложение висит — это три разные беды.

cd "$(dirname "$0")/.."
ROOT="$(pwd)"

SOCK="${DADES_SOCKET:-/run/dades/gunicorn.sock}"
# Сразу после перезапуска сокета может не быть ещё секунду-другую: systemd
# уже сказал «работает», а gunicorn ещё поднимает рабочие процессы. Поэтому
# не спрашиваем один раз, а ждём — молчание в первую секунду не поломка.
WAIT="${DADES_PROBE_WAIT:-20}"

# Домен берём из .env, чтобы проверка не разошлась с настройками сайта.
HOST="localhost"
if [ -f "$ROOT/.env" ]; then
    FROM_ENV="$(sed -n 's/^DJANGO_ALLOWED_HOSTS=//p' "$ROOT/.env" | tail -1 | tr -d '"'"'"' ' | cut -d, -f1)"
    # «.da-des.ru» в настройках означает домен со всеми поддоменами,
    # а в заголовке Host точка спереди не нужна.
    [ -n "$FROM_ENV" ] && HOST="${FROM_ENV#.}"
fi

ERR="$(mktemp)"
trap 'rm -f "$ERR"' EXIT

CODE=""
# Считаем не попытки, а секунды: висящее приложение отвечает молчанием
# по десять секунд на попытку, и «двадцать попыток» превратились бы
# в три минуты ожидания вместо двадцати секунд.
END=$((SECONDS + WAIT))
while :; do
    if [ -S "$SOCK" ]; then
        # -q — не читать ~/.curlrc и /etc/curl/curlrc: чужие настройки
        # вроде --retry заставляют curl сходить дважды, и тогда он печатает
        # код каждой попытки подряд. Так «000» однажды превратилось
        # в «000000» и напугало сильнее самой ошибки.
        RAW="$(curl -q -sS -o /dev/null -w '%{http_code}' --max-time 5 \
            --unix-socket "$SOCK" \
            -H "Host: $HOST" \
            -H 'X-Forwarded-Proto: https' \
            http://localhost/ 2>"$ERR" || true)"
        # На всякий случай оставляем только последний код: три цифры.
        CODE="$(printf '%s' "$RAW" | tr -cd '0-9' | tail -c 3)"
        [ -n "$CODE" ] || CODE=000
        [ "$CODE" = "000" ] || break
    fi
    [ "$SECONDS" -ge "$END" ] && break
    sleep 1
done

if [ -z "$CODE" ]; then
    echo "нет-сокета"
    echo "Сокет $SOCK не появился за ${WAIT} с." >&2
    exit 0
fi

if [ "$CODE" = "000" ]; then
    tail -1 "$ERR" >&2
fi

echo "$CODE"
